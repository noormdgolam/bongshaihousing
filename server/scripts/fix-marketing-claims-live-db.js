async function fixDb(dbName) {
  console.log(`\n========================================================`);
  console.log(`   FIXING DATABASE: ${dbName}`);
  console.log(`========================================================`);
  const conn = await mysql.createConnection({
    host: 'bongshaihousing.com',
    port: 3306,
    user: dbName,
    password: process.env.DB_PASSWORD,
    database: dbName,
  });

  // 1. products.meta_description <- products.json (same shape as the existing
  //    20260829000001_sync_products_meta_description_from_seed.js migration)
  let metaCount = 0;
  for (const p of products) {
    if (!p.modelNumber || !p.description) continue;
    const desc = p.description.trim();
    if (!desc) continue;
    const [result] = await conn.query(
      'UPDATE products SET meta_description = ? WHERE model_number = ? AND meta_description <> ?',
      [desc, p.modelNumber, desc]
    );
    if (result.affectedRows > 0) {
      metaCount++;
      console.log(`  [meta_description] ${p.modelNumber} -> updated`);
    }
  }
  console.log(`  products.meta_description: ${metaCount} row(s) updated`);

  // 2. products.description: drop the "64 districts" suffix generated by the
  //    (now-fixed) regenerate_product_descriptions.py template
  const [descRows] = await conn.query(
    "SELECT id, model_number, description FROM products WHERE description LIKE '%delivery across all 64 districts.%'"
  );
  for (const row of descRows) {
    const fixed = row.description.replace(
      'delivery across all 64 districts.',
      'delivery nationwide.'
    );
    await conn.query('UPDATE products SET description = ? WHERE id = ?', [fixed, row.id]);
    console.log(`  [description] id=${row.id} ${row.model_number}: "...${row.description.slice(-60)}" -> "...${fixed.slice(-50)}"`);
  }
  console.log(`  products.description: ${descRows.length} row(s) updated`);

  // 3. faqs
  const faqFixes = FAQ_FIXES[dbName] || [];
  for (const fix of faqFixes) {
    const [before] = await conn.query('SELECT question, answer FROM faqs WHERE id = ?', [fix.id]);
    if (before.length === 0) {
      console.log(`  [faqs] id=${fix.id} not found, skipping`);
      continue;
    }
    await conn.query('UPDATE faqs SET question = ?, answer = ? WHERE id = ?', [fix.question, fix.answer, fix.id]);
    console.log(`  [faqs] id=${fix.id}: "${before[0].question}" -> "${fix.question}"`);
  }

  // 4. team_members
  const teamFixes = TEAM_MEMBER_FIXES[dbName] || [];
  for (const fix of teamFixes) {
    const [before] = await conn.query('SELECT name, bio, role FROM team_members WHERE id = ?', [fix.id]);
    if (before.length === 0) {
      console.log(`  [team_members] id=${fix.id} not found, skipping`);
      continue;
    }
    if (fix.role) {
      await conn.query('UPDATE team_members SET bio = ?, role = ? WHERE id = ?', [fix.bio, fix.role, fix.id]);
      console.log(`  [team_members] id=${fix.id} (${before[0].name}): role "${before[0].role}" -> "${fix.role}"`);
    } else {
      await conn.query('UPDATE team_members SET bio = ? WHERE id = ?', [fix.bio, fix.id]);
    }
    console.log(`  [team_members] id=${fix.id} (${before[0].name}): bio updated`);
  }

  await conn.end();
}

(async () => {
  const only = process.argv[2]; // optional: 'abongsha_bongshai_app' or 'abongsha_bongshai_prod'
  const targets = only ? [only] : ['abongsha_bongshai_app', 'abongsha_bongshai_prod'];
  for (const dbName of targets) {
    await fixDb(dbName);
  }
  console.log(`\nLive DB fix complete for: ${targets.join(', ')}.`);
})().catch((e) => {
  console.error('Fix error:', e);
  process.exit(1);
});
